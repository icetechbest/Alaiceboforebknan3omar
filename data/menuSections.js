const FOOTER = "『 SONG BOT v2.0 』";

// بيبني قائمة الأقسام القصيرة اللي بتتبعت أول مرة يكتب .اوامر
function buildCategoryListText() {
    let msg = `✦━───━ 📜 SONG BOT MENU 📜 ━───━✦\n`;
    msg += `اختار قسم عشان تشوف أوامره (ابعت الرقم أو اسم القسم):\n`;
    msg += `✦━──── ❖ ────━✦\n`;
    for (const s of SECTIONS) {
        msg += `${s.key}️⃣ ${s.emoji} ${s.label}\n`;
    }
    msg += `✦━──── ❖ ────━✦\n`;
    msg += `↩️ رد برقم القسم (1-${SECTIONS.length}) خلال 5 دقايق، أو اكتب اسم القسم.\n`;
    msg += FOOTER;
    return msg;
}

// بيلاقي القسم المطلوب سواء بالرقم أو بجزء من اسمه/عنوانه (يقبل بحث مرن)
function findSection(input) {
    if (!input) return null;
    const q = input.trim();
    if (!q) return null;

    const byKey = SECTIONS.find(s => s.key === q);
    if (byKey) return byKey;

    const qLower = q.toLowerCase();
    return SECTIONS.find(s =>
        s.label.toLowerCase().includes(qLower) ||
        s.title.toLowerCase().includes(qLower) ||
        qLower.includes(s.label.toLowerCase())
    ) || null;
}

// بيبني نص قسم واحد كامل (عنوانه + أوامره)
function buildSectionText(section) {
    let msg = `✦━──── ❖ ────━✦\n`;
    msg += `${section.title}\n`;
    msg += `✦━──── ❖ ────━✦\n`;
    msg += `${section.body}\n`;
    msg += `✦━──── ❖ ────━✦\n`;
    msg += `↩️ اكتب رقم قسم تاني، أو "رجوع" للقائمة الرئيسية.\n`;
    msg += FOOTER;
    return msg;
}

// بيبني رسالة قائمة تفاعلية أصلية (list message) لواتساب لاختيار قسم — بنحط
// نفس النص العادي كـ body (بيظهر دايمًا)، والأزرار/القائمة المنسدلة كطبقة
// إضافية بس. السبب: قوائم واتساب التفاعلية بقت مش مضمونة 100% على كل نسخة/نوع
// حساب (واتساب بتقلل الدعم ليها بره الـ Business API)، فلو معرضتش تفاعليًا
// عند حد معين، النص العادي (وبعده نظام الرد بالرقم) بيفضل شغال زي أي وقت.
function buildCategoryListMessage() {
    const rows = SECTIONS.map(s => ({
        title: `${s.emoji} ${s.label}`,
        rowId: s.key,
        description: `اضغط عشان تشوف أوامر ${s.label}`
    }));
    return {
        text: buildCategoryListText(),
        footer: FOOTER,
        title: '📜 قائمة أقسام البوت',
        buttonText: 'عرض الأقسام',
        sections: [{ title: 'اختار قسم', rows }]
    };
}

// 🛡️ بيحاول يبعت القائمة التفاعلية، ولو فشل الإرسال بالكامل (بعض نسخ/حسابات
// واتساب بترفض شكل الرسالة دي تمامًا فمبيوصلش ولا حتى النص) بيرجع تلقائيًا
// يبعت نفس المحتوى كنص عادي بسيط عشان المستخدم ميفضلش من غير رد خالص.
async function sendCategoryMenu(sock, chatId, quoted) {
    try {
        const res = await sock.sendMessage(chatId, buildCategoryListMessage(), { quoted });
        if (!res) throw new Error('sendMessage رجع نتيجة فاضية');
        return res;
    } catch (e) {
        console.log('⚠️ فشل إرسال القائمة التفاعلية لـ .اوامر، هيتبعت نص عادي بدلاً منها:', e?.message || e);
        return sock.sendMessage(chatId, { text: buildCategoryListText() }, { quoted });
    }
}

// بيتحقق إن النص المكتوب فعلاً طلب رجوع للقائمة الرئيسية
function isBackToMenuRequest(text) {
    const q = (text || '').trim().toLowerCase();
    return ['رجوع', 'القائمة', 'رجوع للقائمة', 'menu', 'back'].includes(q);
}

module.exports = { SECTIONS, buildCategoryListText, buildCategoryListMessage, sendCategoryMenu, findSection, buildSectionText, isBackToMenuRequest };
